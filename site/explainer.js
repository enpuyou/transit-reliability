/* Interactive walk-through of how arrival and departure times are estimated, drawn from example.json
   (generated by scripts/make_site_example.py from one real trip using the pipeline's own functions).
   All text is inserted as text, never as HTML. */
(function () {
  "use strict";
  var NS = "http://www.w3.org/2000/svg";
  var STEPS = ["1. Two lists, one ruler", "2. Put a GPS dot on the ruler", "3. The bus, report by report", "4. Arrived and left", "5. What can go wrong"];
  var PT = new Intl.DateTimeFormat("en-US", { timeZone: "America/Los_Angeles", hour: "numeric", minute: "2-digit", second: "2-digit", hourCycle: "h12" });
  var state = { ex: null, step: 0, report: 0 };

  function h(tag, attrs, kids) {
    var n = document.createElement(tag);
    Object.keys(attrs || {}).forEach(function (k) { if (k === "text") n.textContent = attrs[k]; else n.setAttribute(k, attrs[k]); });
    (kids || []).forEach(function (c) { if (c !== null && c !== undefined) n.appendChild(typeof c === "string" ? document.createTextNode(c) : c); });
    return n;
  }
  function sv(tag, attrs, text) {
    var n = document.createElementNS(NS, tag);
    Object.keys(attrs || {}).forEach(function (k) { n.setAttribute(k, attrs[k]); });
    if (text !== undefined) n.textContent = text;
    return n;
  }
  function t(ts) { return PT.format(new Date(ts * 1000)); }          /* 4:25:10 PM, Seattle time */
  function ft(n) { return Math.round(n).toLocaleString("en-US") + " ft"; }
  function clean(s) { return String(s).replace(/\s+/g, " "); }

  function geometry(ex) {
    var d0 = ex.stop.dist_ft - 950, d1 = ex.stop.dist_ft + 950, L = 30, R = 30, W = 900;
    return { d0: d0, d1: d1, W: W, x: function (d) { return L + (d - d0) / (d1 - d0) * (W - L - R); } };
  }

  /* ---------- the ruler diagram ---------- */
  function ruler(ex, step, idx) {
    var g = geometry(ex), x = g.x, svg = sv("svg", { viewBox: "0 0 900 " + (step >= 3 ? 290 : (step === 2 ? 245 : 150)), role: "img", "aria-label": "Route ruler with stops and bus reports" });
    var base = 120;
    svg.appendChild(sv("line", { x1: 20, x2: 880, y1: base, y2: base, stroke: "var(--muted)", "stroke-width": 2 }));
    svg.appendChild(sv("text", { x: 20, y: 18, "font-size": 12, fill: "var(--muted)" }, "← back toward the start of the route"));
    svg.appendChild(sv("text", { x: 880, y: 18, "font-size": 12, fill: "var(--muted)", "text-anchor": "end" }, "toward the end of the route →"));
    ex.route_points_near.forEach(function (p) {
      if (p.dist_ft < g.d0 || p.dist_ft > g.d1) return;
      svg.appendChild(sv("circle", { cx: x(p.dist_ft), cy: base, r: 3.2, fill: "var(--c4)" }));
    });
    svg.appendChild(sv("text", { x: 22, y: base + 18, "font-size": 11, fill: "var(--c4)" }, "● dots of the route line (each has a latitude, longitude and its feet from the start)"));
    ex.stops_near.forEach(function (s) {
      if (s.dist_ft < g.d0 || s.dist_ft > g.d1) return;
      var isMain = s.sequence === ex.stop.sequence, cx = x(s.dist_ft);
      svg.appendChild(sv("rect", { x: cx - 6, y: base - 38, width: 12, height: 12, fill: isMain ? "var(--accent)" : "var(--c2)" }));
      svg.appendChild(sv("line", { x1: cx, x2: cx, y1: base - 26, y2: base, stroke: isMain ? "var(--accent)" : "var(--c2)", "stroke-dasharray": "2 3" }));
      var label = (isMain ? "STOP: " : "stop: ") + clean(s.name).slice(0, 26);
      var anchor = cx > 740 ? "end" : (cx < 160 ? "start" : "middle"), lx = anchor === "end" ? cx + 8 : (anchor === "start" ? cx - 8 : cx);
      svg.appendChild(sv("text", { x: lx, y: base - 46, "font-size": 12, "font-weight": isMain ? 700 : 400, fill: "var(--fg)", "text-anchor": anchor }, label));
      svg.appendChild(sv("text", { x: lx, y: base - 61, "font-size": 11, fill: "var(--muted)", "text-anchor": anchor }, ft(s.dist_ft) + " from the start"));
    });
    if (step >= 3) {
      var a = ex.stop.dist_ft - ex.arrive_ft_before, d = ex.stop.dist_ft + ex.depart_ft_after;
      [[a, "arrived: " + ex.arrive_ft_before + " ft before the stop point", "var(--c3)", -1], [d, "left: " + ex.depart_ft_after + " ft past it", "var(--c5)", 1]].forEach(function (l) {
        svg.appendChild(sv("line", { x1: x(l[0]), x2: x(l[0]), y1: base - 20, y2: base + 128, stroke: l[2], "stroke-width": 2, "stroke-dasharray": "5 3" }));
        svg.appendChild(sv("text", { x: x(l[0]) + (l[3] < 0 ? -6 : 6), y: base + 142, "font-size": 11, fill: l[2], "text-anchor": l[3] < 0 ? "end" : "start" }, l[1]));
      });
    }
    /* group reports that sit at the same spot (the bus standing still) */
    var groups = [];
    ex.reports.forEach(function (r, i) {
      var last = groups[groups.length - 1];
      if (last && Math.abs(last.dist - r.dist_ft) < 1) { last.items.push({ r: r, i: i }); } else { groups.push({ dist: r.dist_ft, items: [{ r: r, i: i }] }); }
    });
    var show = step >= 2;
    if (show) {
      groups.forEach(function (gp, k) {
        var cx = x(gp.dist), cy = 160, hit = gp.items.some(function (it) { return it.i === idx; });
        var mark = step === 3 ? hit : (step === 2 ? gp.items.some(function (it) { return it.r.ts === ex.projection.report_ts; }) : false);
        var bracket = step >= 3 && gp.items.some(function (it) { return it.r.ts === ex.arrival.before.ts || it.r.ts === ex.arrival.after.ts; });
        svg.appendChild(sv("line", { x1: cx, x2: cx, y1: base, y2: cy - 7, stroke: "var(--line)" }));
        svg.appendChild(sv("circle", { cx: cx, cy: cy, r: mark ? 9 : (bracket ? 7 : 5), fill: mark ? "var(--c2)" : (bracket ? "var(--c3)" : "var(--c1)"), stroke: "var(--card)", "stroke-width": 1.5 }));
        var times = gp.items.map(function (it) { return t(it.r.ts).replace(" PM", "").replace(" AM", ""); });
        var up = k % 2 === 0;
        svg.appendChild(sv("text", { x: cx, y: up ? cy + 22 : cy + 36, "font-size": 11, fill: "var(--fg)", "text-anchor": "middle" }, times.length > 1 ? times[0] + "–" + times[times.length - 1] : times[0]));
        if (times.length > 1) svg.appendChild(sv("text", { x: cx, y: up ? cy + 34 : cy + 48, "font-size": 10, fill: "var(--muted)", "text-anchor": "middle" }, "standing still"));
      });
      svg.appendChild(sv("text", { x: 22, y: step >= 3 ? 282 : 232, "font-size": 11, fill: "var(--c1)" }, "● the bus's GPS reports (Seattle time, pm), placed by how far along the route they are"));
    }
    return svg;
  }

  /* ---------- step 2: a close-up of one GPS dot landing on one piece of the route line ---------- */
  function closeup(ex) {
    var pr = ex.projection, pts = ex.route_points_near, A = pr.a, B = pr.b;
    var kx = pr.feet_per_degree_latitude * pr.longitude_shrink, ky = pr.feet_per_degree_latitude;
    function px(p) { return (p.lon - A.lon) * kx; }
    function py(p) { return (p.lat - A.lat) * ky; }
    var near = pts.filter(function (p) { return Math.abs(p.dist_ft - A.dist_ft) <= 600; });
    var xs = near.map(px).concat([0, px(B)]), ys = near.map(py).concat([0, py(B)]);
    var minx = Math.min.apply(null, xs), maxx = Math.max.apply(null, xs), miny = Math.min.apply(null, ys), maxy = Math.max.apply(null, ys);
    var w = 900, hgt = 250, sc = Math.min(180 / Math.max(maxx - minx, 40), (hgt - 60) / Math.max(maxy - miny, 40));
    var ox = 250 - ((maxx - minx) * sc) / 2;
    function X(v) { return ox + (v - minx) * sc; }
    function Y(v) { return hgt - 30 - (v - miny) * sc; }
    var svg = sv("svg", { viewBox: "0 0 " + w + " " + hgt, role: "img", "aria-label": "A GPS report placed onto a piece of the route line" });
    svg.appendChild(sv("text", { x: 20, y: 18, "font-size": 12, fill: "var(--muted)" }, "Close-up map, looking down on the road (north is up): the route line's dots, and one GPS report"));
    var d = near.map(function (p, i) { return (i ? "L" : "M") + X(px(p)).toFixed(1) + " " + Y(py(p)).toFixed(1); }).join(" ");
    svg.appendChild(sv("path", { d: d, fill: "none", stroke: "var(--c4)", "stroke-width": 2 }));
    near.forEach(function (p) { svg.appendChild(sv("circle", { cx: X(px(p)), cy: Y(py(p)), r: p.dist_ft === A.dist_ft || p.dist_ft === B.dist_ft ? 5.5 : 3, fill: "var(--c4)" })); });
    var ax = X(0), ay = Y(0), bx = X(px(B)), by = Y(py(B));
    var fx = ax + pr.fraction * (bx - ax), fy = ay + pr.fraction * (by - ay), nx = -(by - ay), ny = bx - ax, nl = Math.hypot(nx, ny) || 1, side = nx < 0 ? -1 : 1;
    var dx = fx + side * nx / nl * 26, dy = fy + side * ny / nl * 26;   /* drawn farther from the line than the real offset, for visibility */
    svg.appendChild(sv("line", { x1: dx, y1: dy, x2: fx, y2: fy, stroke: "var(--c2)", "stroke-dasharray": "3 3" }));
    svg.appendChild(sv("circle", { cx: dx, cy: dy, r: 8, fill: "var(--c2)" }));
    svg.appendChild(sv("circle", { cx: fx, cy: fy, r: 4, fill: "var(--card)", stroke: "var(--c2)", "stroke-width": 2 }));
    var lx = 440;
    [[ay, "dot A  =  " + ft(A.dist_ft) + " from the start", "var(--c4)", ax, ay], [by, "dot B  =  " + ft(B.dist_ft) + " from the start", "var(--c4)", bx, by], [dy, "the bus report " + pr.offset_ft + " ft from the line (drawn bigger and farther away so you can see it)", "var(--c2)", dx, dy], [fy, "its closest spot on the piece: " + Math.round(pr.fraction * 100) + "% of the way from A to B  =  " + ft(pr.dist_ft), "var(--fg)", fx, fy]].forEach(function (l, i) {
      var ty = 60 + i * 44;
      svg.appendChild(sv("line", { x1: l[3] + 8, y1: l[4], x2: lx - 6, y2: ty - 4, stroke: "var(--line)" }));
      svg.appendChild(sv("text", { x: lx, y: ty, "font-size": 12, fill: l[2] }, l[1]));
    });
    return svg;
  }

  /* ---------- step 4: the 30-second window ---------- */
  function timeline(ex) {
    var a = ex.arrival, d = ex.departure, t0 = a.before.ts, t1 = a.after.ts, w = 860, svg = sv("svg", { viewBox: "0 0 900 120", role: "img", "aria-label": "Estimated arrival and departure inside the gap between two reports" });
    function X(ts) { return 20 + (ts - t0) / (t1 - t0) * (w - 20); }
    svg.appendChild(sv("rect", { x: X(t0), y: 44, width: X(t1) - X(t0), height: 10, fill: "var(--soft)", stroke: "var(--line)" }));
    svg.appendChild(sv("circle", { cx: X(t0), cy: 49, r: 7, fill: "var(--c3)" }));
    svg.appendChild(sv("circle", { cx: X(t1), cy: 49, r: 7, fill: "var(--c3)" }));
    svg.appendChild(sv("text", { x: X(t0), y: 78, "font-size": 12, fill: "var(--fg)", "text-anchor": "start" }, "report " + t(t0) + " (" + ft(a.before.dist_ft) + ")"));
    svg.appendChild(sv("text", { x: X(t1), y: 78, "font-size": 12, fill: "var(--fg)", "text-anchor": "end" }, "report " + t(t1) + " (" + ft(a.after.dist_ft) + ")"));
    [[a, "arrived", "var(--c3)", 24], [d, "left", "var(--c5)", 12]].forEach(function (m) {
      svg.appendChild(sv("line", { x1: X(m[0].estimate_ts), x2: X(m[0].estimate_ts), y1: 30, y2: 70, stroke: m[2], "stroke-width": 3 }));
      svg.appendChild(sv("text", { x: X(m[0].estimate_ts) + 6, y: m[3], "font-size": 12, "font-weight": 700, fill: m[2] }, m[1] + " ≈ " + t(m[0].estimate_ts)));
    });
    svg.appendChild(sv("text", { x: 20, y: 108, "font-size": 12, fill: "var(--muted)" }, "the true times are somewhere in this " + (t1 - t0) + "-second gap; we keep the whole range and mark our best guess inside it"));
    return svg;
  }

  /* ---------- the text for each step ---------- */
  function para(text) { return h("p", { text: text }); }
  function eq(text) { return h("div", { "class": "how-eq", text: text }); }
  function bullets(list) { return h("ul", {}, list.map(function (x) { return h("li", { text: x }); })); }
  function reportLine(ex, r, rel) {
    return "At " + t(r.ts) + " the bus was " + ft(r.dist_ft) + " from the start of the route: " + (Math.abs(rel) < 1 ? "exactly at" : ft(Math.abs(rel)) + (rel < 0 ? " before" : " past")) + " the stop point.";
  }
  function bodyFor(ex, step) {
    var s = ex.stop, pr = ex.projection, a = ex.arrival, d = ex.departure, w = pr.window, out = [];
    if (step === 0) {
      out.push(para("The agency's timetable file gives us two lists, and they share one ruler: feet from the start of the route."));
      out.push(bullets([
        "The route line (purple dots): " + ex.n_route_points + " dots that trace the road the bus drives, bend by bend. Each dot has a latitude, a longitude, and its distance from the start of the route. The dots are NOT stops.",
        "The stops (squares): a separate, shorter list, " + ex.n_stops + " stops on this trip. The timetable states each stop's distance on the same ruler: \"" + clean(s.name) + "\" is " + ft(s.dist_ft) + " from the start.",
        "Because both are measured in feet from the start, comparing a bus with a stop is just a subtraction. The live GPS report is the only thing missing a distance, so that is what we have to work out (next step)."
      ]));
    } else if (step === 1) {
      out.push(para("A bus's GPS report is only a latitude and longitude, so we compute where on the ruler it falls. Here is one real report, from " + t(pr.report_ts) + ":"));
      out.push(bullets([
        "Flatten the map into feet. One degree of latitude is " + Math.round(pr.feet_per_degree_latitude).toLocaleString("en-US") + " ft; a degree of longitude is shorter in Seattle (" + pr.longitude_shrink + " times as long). Measured from the route's first dot, the report is " + Math.abs(pr.east_ft).toLocaleString("en-US") + " ft " + (pr.east_ft < 0 ? "west" : "east") + " and " + Math.abs(pr.north_ft).toLocaleString("en-US") + " ft " + (pr.north_ft < 0 ? "south" : "north") + ".",
        "Find the closest short straight piece of the route line. It is piece #" + pr.piece_index + ": it starts at dot A (" + ft(pr.a.dist_ft) + " from the start) and ends at dot B (" + ft(pr.b.dist_ft) + "); it is " + pr.piece_length_ft + " ft long. The report is only " + pr.offset_ft + " ft from it, so it is clearly on the route.",
        "Slide the report straight onto that piece: it lands " + Math.round(pr.fraction * 100) + "% of the way from A to B."
      ]));
      out.push(eq("distance = " + pr.a.dist_ft.toLocaleString("en-US") + " + " + pr.fraction + " × (" + pr.b.dist_ft.toLocaleString("en-US") + " − " + pr.a.dist_ft.toLocaleString("en-US") + ") = " + pr.dist_ft.toLocaleString("en-US") + " ft"));
      out.push(para("The stop is at " + ft(s.dist_ft) + ", so this bus is " + ft(pr.dist_ft - s.dist_ft) + " past the stop."));
      out.push(para("We do not test every piece every time. For the first report of a trip we check all " + pr.n_pieces + " pieces; afterwards only a window around where the bus just was: from " + w.back_ft + " ft behind its last position up to the farthest it could have gone (" + w.max_speed_ft_s + " ft per second × " + w.elapsed_s + " s + " + w.slack_ft + " ft). Here that is " + w.lo_ft.toLocaleString("en-US") + " to " + w.hi_ft.toLocaleString("en-US") + " ft, " + w.pieces + " of the " + pr.n_pieces + " pieces. This stops a route that doubles back on itself from fooling us, and reports more than 250 ft from the line are thrown away as GPS glitches."));
    } else if (step === 2) {
      var r = ex.reports[state.report], rel = r.dist_ft - s.dist_ft;
      out.push(para("Move the slider to follow the bus past the stop. Each report is placed on the ruler with the calculation from step 2."));
      var slider = h("input", { type: "range", min: 0, max: ex.reports.length - 1, value: state.report, "aria-label": "GPS report number" });
      var label = h("span", { text: "Report " + (state.report + 1) + " of " + ex.reports.length }), line = h("p", { id: "how-report-line", text: reportLine(ex, r, rel) });
      slider.addEventListener("input", function () {
        state.report = Number(slider.value);
        var rr = ex.reports[state.report];
        label.textContent = "Report " + (state.report + 1) + " of " + ex.reports.length;
        line.textContent = reportLine(ex, rr, rr.dist_ft - s.dist_ft);
        document.getElementById("how-ruler").replaceChildren(ruler(ex, 3, state.report));
      });
      out.push(h("div", { "class": "how-ctl" }, [label, slider]));
      out.push(line);
      out.push(para("Notice the bus standing still at the same spot for several reports (about " + ft(s.dist_ft - ex.reports[1].dist_ft) + " before the stop point), then pulling away. Reports are every 15 seconds when we catch them all; we download the agency's feed about every 21 seconds, so we see roughly two out of three, which is why some gaps are 30 seconds."));
    } else if (step === 3) {
      out.push(para("We call the bus ARRIVED when it reaches " + ex.arrive_ft_before + " ft before the stop point, and LEFT when it is " + ex.depart_ft_after + " ft past it (the two dashed lines). I chose those distances to allow for GPS wobble and the length of a bus; they are settings, not measurements."));
      out.push(para("The arrival line (" + ft(a.threshold_ft) + ") falls between two reports. The bus covered " + ft(a.after.dist_ft - a.before.dist_ft) + " in " + (a.after.ts - a.before.ts) + " seconds, and the line is " + ft(a.threshold_ft - a.before.dist_ft) + " into that stretch, " + Math.round(a.fraction * 100) + "% of the way:"));
      out.push(eq("arrived ≈ " + t(a.before.ts) + " + " + Math.round(a.fraction * 100) + "% × " + (a.after.ts - a.before.ts) + " s = " + t(a.estimate_ts)));
      out.push(para("The departure line (" + ft(d.threshold_ft) + ") is " + ft(d.threshold_ft - d.before.dist_ft) + " into the same stretch, " + Math.round(d.fraction * 100) + "% of the way:"));
      out.push(eq("left ≈ " + t(d.before.ts) + " + " + Math.round(d.fraction * 100) + "% × " + (d.after.ts - d.before.ts) + " s = " + t(d.estimate_ts)));
      out.push(para("The timetable said " + t(s.scheduled_arrival_ts) + ". So this bus arrived about " + Math.round((a.estimate_ts - s.scheduled_arrival_ts) / 60 * 10) / 10 + " minutes late, and left about " + Math.round((d.estimate_ts - s.scheduled_departure_ts) / 60 * 10) / 10 + " minutes late. The system's stored values for this stop are the same as this hand calculation."));
    } else {
      out.push(para("Every arrival and departure on this website is an estimate with a range. What can go wrong, using this very example:"));
      out.push(bullets([
        "Steady speed is assumed between two reports. If the bus really crawled and then sped up, the true time is elsewhere in the range, which is why we keep the range (here " + (a.after.ts - a.before.ts) + " seconds wide).",
        "This bus stood about " + ft(s.dist_ft - ex.reports[1].dist_ft) + " short of the stop point for about " + (ex.reports[3].ts - ex.reports[1].ts) + " seconds. It may have been loading just short of the sign or waiting at a traffic light; GPS cannot tell. Our rule counts it as arrived when it pulled up to within " + ex.arrive_ft_before + " ft, which is later than the first moment it stopped, so our time can be about half a minute late in a case like this.",
        "We only see about two of every three reports (the bus reports every 15 s; we download every 21 s), which widens ranges.",
        "At the first stop the bus is parked, so only its departure can be measured. At the last stop the agency's data for the trip usually ends before the bus gets there, so the arrival is rarely measurable.",
        "Two extra hints tighten some estimates: the agency's \"next stop\" counter and a \"stopped\" flag. We never let them contradict the GPS position.",
        "None of this has been checked against a stopwatch. A ride test (someone noting real arrival times) would do that; it has not been done."
      ]));
    }
    return out;
  }

  function redraw() {
    var ex = state.ex, host = document.getElementById("how");
    host.replaceChildren();
    var steps = h("div", { "class": "how-steps", role: "tablist" }, STEPS.map(function (label, i) {
      var b = h("button", { type: "button", "class": i === state.step ? "on" : "", text: label });
      b.addEventListener("click", function () { state.step = i; redraw(); });
      return b;
    }));
    host.appendChild(steps);
    host.appendChild(h("div", { id: "how-ruler" }, [ruler(ex, state.step + 1, state.step === 2 ? state.report : -1)]));
    if (state.step === 1) host.appendChild(closeup(ex));
    if (state.step === 3) host.appendChild(timeline(ex));
    var text = h("div", { "class": "how-text" }, bodyFor(ex, state.step));
    host.appendChild(text);
    var prev = h("button", { type: "button", text: "← Back" }), next = h("button", { type: "button", text: "Next →" });
    prev.disabled = state.step === 0; next.disabled = state.step === STEPS.length - 1;
    prev.addEventListener("click", function () { state.step--; redraw(); });
    next.addEventListener("click", function () { state.step++; redraw(); });
    host.appendChild(h("div", { "class": "how-nav" }, [prev, next]));
  }

  fetch("example.json", { cache: "no-store" }).then(function (r) {
    if (!r.ok) throw new Error("example.json: HTTP " + r.status);
    return r.json();
  }).then(function (ex) {
    state.ex = ex;
    var hit = ex.reports.findIndex(function (r) { return r.ts === ex.projection.report_ts; });
    state.report = Math.max(0, hit);
    redraw();
  }).catch(function (e) {
    var host = document.getElementById("how");
    if (host) host.replaceChildren(h("p", { "class": "note", text: "The worked example could not be loaded (" + e.message + ")." }));
  });
})();
